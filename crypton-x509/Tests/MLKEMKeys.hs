-- | An ML-KEM-512 key pair as OpenSSL 3.6 writes it, the private key in
-- the @both@ form of RFC 9935 Section 6.
--
--   openssl genpkey -algorithm ML-KEM-512 -outform DER
module MLKEMKeys (
    opensslMLKEM512,
    opensslMLKEM512Pub,
) where

import qualified Data.ByteString as BS

import Data.ByteArray.Encoding (Base (Base16), convertFromBase)

hex :: String -> BS.ByteString
hex s = case convertFromBase Base16 (BS.pack (map (fromIntegral . fromEnum) s)) of
    Left e -> error e
    Right b -> b

