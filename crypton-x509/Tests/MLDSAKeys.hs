-- | ML-DSA private keys in PKCS#8, as OpenSSL 3.6.4 writes them.
--
-- Not generated here: the point of these is that another implementation
-- made them.  A round trip through this library's own encoder and decoder
-- says only that the two halves agree; these say that what comes out is
-- what the rest of the world reads.
--
--   openssl genpkey -algorithm ML-DSA-44 | openssl pkey -outform DER
--
-- OpenSSL writes the @both@ form of RFC 9881 section 6: the seed and the
-- expanded key in a SEQUENCE.
module MLDSAKeys (
    opensslMLDSA44,
    opensslMLDSA65,
    opensslMLDSA87,
) where

import qualified Data.ByteString as BS

import Data.ByteArray.Encoding (Base (Base16), convertFromBase)

hex :: String -> BS.ByteString
hex s = case convertFromBase Base16 (BS.pack (map (fromIntegral . fromEnum) s)) of
    Left e -> error e
    Right b -> b

